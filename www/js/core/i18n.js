function detectLang() {
	try {
		const l = (navigator.languages && navigator.languages[0]) || navigator.language || '';
		if (/^ko/i.test(l)) return 'ko';
		if (/^ja/i.test(l)) return 'ja';
		return 'en';
	} catch (e) {
		return 'en';
	}
}

